// Which generated pages are built at all.
//
// On 2026-09-24 Google began its September 2026 spam update. Two days later
// this site's impressions went from about 800 a day to under 5 and stayed
// there, with no manual action, every page still indexed and nothing wrong in
// the responses. What the site had was 13,036 pages, about 11,000 of them
// built in three weeks from tables — a value plugged into a template, a pair
// of cities, a pair of units. That is the shape the scaled-content policy
// describes, and it is the most likely reason.
//
// So the large template sections are cut down to what has earned its place:
//
//   - every page Google showed at least once in the three months before the
//     drop (src/data/gsc-pages.txt), in any section;
//   - every tool, every category and section hub;
//   - the small reference sections whole, where each page is a distinct
//     object (a port, a drill size, an HTTP status) rather than a number
//     substituted into the same sentence;
//   - in the large sections, the pages a reader navigates by: the city pages,
//     the pairs the time-difference hub features, each ingredient, each paper
//     size, each converter category and the conversions between its everyday
//     units.
//
// Everything else is not built. It 404s, drops out of the sitemap and the
// search index, and every link that pointed at it is unlinked by build.mjs.
import fs from 'node:fs';
import { CITIES, FEATURED } from './gen/time-difference.mjs';

const GSC = new Set(
  fs.readFileSync(new URL('./data/gsc-pages.txt', import.meta.url), 'utf8')
    .split('\n').map((l) => l.trim()).filter((l) => l.startsWith('/')),
);

// The sections whose pages are generated by the thousand.
const PRUNED = new Set(['convert', 'time-difference', 'cooking', 'color', 'paper', 'roman', 'ascii']);

const CITY = new Set(CITIES.map((c) => c[0]));
const FEATURED_PAIRS = new Set(FEATURED.map(([a, b]) => `${a}-${b}`));

// Converter categories and the other /convert/ hubs: no "-to-" in the slug.
const CONVERT_HUB = /^\/convert\/[a-z-]+\/$/;

// The everyday units in each converter category. Every pair between two of
// them keeps its page, so each category hub still lists the conversions people
// come to a converter for; a pair involving arcseconds, mach or barrels stays
// only if Google showed it.
const CORE_UNITS = {
  length: ['meters', 'kilometers', 'centimeters', 'millimeters', 'miles', 'feet', 'inches'],
  weight: ['kilograms', 'grams', 'pounds', 'ounces', 'stones'],
  data: ['bytes', 'kilobytes', 'megabytes', 'gigabytes', 'terabytes', 'bits'],
  area: ['square-meters', 'square-kilometers', 'square-miles', 'square-feet', 'acres', 'hectares'],
  volume: ['liters', 'milliliters', 'gallons', 'cups', 'fluid-ounces', 'tablespoons', 'teaspoons'],
  speed: ['meters-per-second', 'kilometers-per-hour', 'miles-per-hour', 'knots'],
  time: ['seconds', 'minutes', 'hours', 'days', 'weeks'],
  pressure: ['kilopascals', 'bars', 'psi', 'atmospheres'],
  energy: ['joules', 'kilojoules', 'calories', 'kilocalories', 'kilowatt-hours'],
  power: ['watts', 'kilowatts', 'horsepower'],
  angle: ['degrees', 'radians'],
  frequency: ['hertz', 'kilohertz', 'megahertz', 'rpm'],
  temperature: ['celsius', 'fahrenheit', 'kelvin'],
  css: ['px', 'rem', 'em', 'pt', 'in', 'cm', 'mm'],
};
const CORE_PAIRS = new Set();
for (const us of Object.values(CORE_UNITS))
  for (const a of us) for (const b of us) if (a !== b) CORE_PAIRS.add(`${a}-to-${b}`);

// The sizes whose pixel dimensions people look up; the rest of the
// /paper/<size>/pixels/ pages restate the size page at another DPI.
const PAPER_PIXELS = new Set(['a0', 'a1', 'a2', 'a3', 'a4', 'a5', 'a6', 'letter', 'legal', 'tabloid']);

export function keep(path) {
  const parts = path.split('/').filter(Boolean);
  if (parts.length <= 1) return true;
  if (!PRUNED.has(parts[0])) return true;
  if (GSC.has(path)) return true;

  const [sec, a, b] = parts;
  switch (sec) {
    case 'convert':
      if (parts.length !== 2) return false;
      return CORE_PAIRS.has(a) || (CONVERT_HUB.test(path) && !a.includes('-to-'));
    case 'time-difference':
      if (a === 'country') return parts.length === 2;
      return parts.length === 2 && (CITY.has(a) || FEATURED_PAIRS.has(a));
    case 'cooking':
      // Ingredient pages; the amount pages all start with a digit.
      return parts.length === 2 && !/^\d/.test(a);
    case 'color':
      // The named-colour and Tailwind hubs and the CSS named colours under
      // them; hex pages only where Google showed them.
      return a === 'name' || a === 'tailwind';
    case 'paper':
      if (parts.length === 2) return true;
      if (a === 'compare') return false;
      return b === 'pixels' && PAPER_PIXELS.has(a);
    default:
      return false;
  }
}
